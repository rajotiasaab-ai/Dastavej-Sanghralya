def get_theme(name: str) -> Dict[str, Any]:
    """Returns the theme dictionary for a given name, defaulting to Liquid Glass."""
    key = (name or "").strip().lower()
    if key in THEMES:
        return THEMES[key]
    if "liquid" in key:
        return THEMES["liquid_glass"]
    if "glass" in key:
        return THEMES["glassy"]
    if "retro" in key:
        return THEMES["retro"]
    if "dark" in key:
        return THEMES["dark"]
    if "light" in key:
        return THEMES["light"]
    if "system" in key:
        return THEMES["liquid_glass"]
    return THEMES["liquid_glass"]
